# Задача 13: Обединение, сечение, разлика и симетрична разлика на две множества

a = set(map(int, input("Въведете елементите на множество A: ").split()))
b = set(map(int, input("Въведете елементите на множество B: ").split()))

print("A =", a)
print("B =", b)
print("Обединение      A | B =", a | b)
print("Сечение         A & B =", a & b)
print("Разлика         A - B =", a - b)
print("Разлика         B - A =", b - a)
print("Симетрична раз. A ^ B =", a ^ b)
